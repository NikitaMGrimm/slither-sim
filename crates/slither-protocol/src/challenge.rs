//! Bounded, closed grammars for the string-copy challenge family.
//!
//! Unknown programs are rejected; no source is evaluated or interpreted generally.

use crate::{DecodeError, ErrorKind};

/// Maximum decoded source size accepted by the prototype.
pub const MAX_SOURCE_BYTES: usize = 256;

pub type ChallengeError = DecodeError;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Grammar {
    ExactTemplate,
    TokenWhitespace,
}

fn error(offset: usize, kind: ErrorKind) -> ChallengeError {
    DecodeError {
        kind,
        opcode: Some(b'6'),
        offset,
    }
}

/// Stock step-4 reply; no automatic fallback to another grammar or algorithm.
pub fn stock(encoded: &[u8], grammar: Grammar) -> Result<[u8; 27], ChallengeError> {
    let mut reply = literal_27(encoded, grammar)?;
    rotate(&mut reply, 4);
    Ok(reply)
}
/// Vlither's step-2 reply, for explicit simulator compatibility use only.
pub fn vlither_27(encoded: &[u8], grammar: Grammar) -> Result<[u8; 27], ChallengeError> {
    let mut reply = literal_27(encoded, grammar)?;
    rotate(&mut reply, 2);
    Ok(reply)
}
fn rotate(reply: &mut [u8], step: i32) {
    let mut rotation = 0;
    for (index, byte) in reply.iter_mut().enumerate() {
        let (base, upper) = if *byte >= b'a' {
            (i32::from(b'a'), i32::from(*byte) - 32)
        } else {
            (i32::from(b'A'), i32::from(*byte))
        };
        let value = upper - i32::from(b'A');
        if index == 0 {
            rotation = 3 + value;
        }
        // JavaScript signed remainder, including punctuation below 'A'.
        *byte = ((value + rotation) % 26 + base) as u8;
        rotation += step + value;
    }
}
fn exact_literals(source: &[u8]) -> Result<[u8; 27], ChallengeError> {
    const PREFIX: &[u8] = b"var a = \"";
    const BETWEEN: &[u8] = b"\";a+=\"";
    const SUFFIX: &[u8] = b"\";for (var i=0;i<27;i++){idba[i]=a.charCodeAt(i);}";
    let second = PREFIX.len() + 5 + BETWEEN.len();
    if source.len() != second + 22 + SUFFIX.len()
        || !source.starts_with(PREFIX)
        || source.get(PREFIX.len() + 5..second) != Some(BETWEEN)
        || source.get(second + 22..) != Some(SUFFIX)
    {
        return Err(error(0, ErrorKind::Syntax));
    }
    let mut reply = [0; 27];
    reply[..5].copy_from_slice(&source[PREFIX.len()..PREFIX.len() + 5]);
    reply[5..].copy_from_slice(&source[second..second + 22]);
    if let Some(index) = reply
        .iter()
        .position(|c| !(b' '..=b'~').contains(c) || matches!(c, b'"' | b'\\'))
    {
        let source_offset = if index < 5 {
            PREFIX.len() + index
        } else {
            second + index - 5
        };
        return Err(error(source_offset * 2, ErrorKind::Literal));
    }
    Ok(reply)
}

/// Only the exact, authored local legacy source generated by the simulator is
/// admitted. This does not claim a general NTL source interpreter or official
/// source selection. See the browser-admission study linked in the README.
pub fn ntl_legacy_24(encoded: &[u8]) -> Result<[u8; 24], ChallengeError> {
    const SOURCE: &[u8] =
        b"var a='ABCDEFGHIJKLMNOPQRSTUVWX';for(var i=0;i<24;i++)idba[i]=a.charCodeAt(i);";
    if encoded.len() != SOURCE.len() * 2 {
        return Err(error(0, ErrorKind::InvalidLength));
    }
    let mut key = 23_u8;
    for (index, &letter) in encoded.iter().enumerate() {
        if !letter.is_ascii_alphabetic() {
            return Err(error(index, ErrorKind::Alphabet));
        }
        let nibble = (letter.to_ascii_lowercase() - b'a' + 26 - key) % 26;
        if nibble > 15 {
            return Err(error(index, ErrorKind::Nibble));
        }
        let expected = if index % 2 == 0 {
            SOURCE[index / 2] >> 4
        } else {
            SOURCE[index / 2] & 15
        };
        if nibble != expected {
            return Err(error(index, ErrorKind::Syntax));
        }
        key = (key + 17) % 26;
    }
    let mut reply = [0; 24];
    let mut rotation = 2_u8;
    for (index, byte) in reply.iter_mut().enumerate() {
        let letter = index as u8;
        *byte = b'A' + (letter + rotation) % 26;
        rotation = (rotation + 3 + letter) % 26;
    }
    Ok(reply)
}

/// Decode a challenge command payload (without its command byte) and solve it.
///
/// Only a declaration, literal append, and the fixed 27-byte copy loop are
/// accepted. Whitespace between tokens is allowed. Literal contents are runtime
/// input, not credentials embedded in the library.
pub fn literal_27(encoded: &[u8], grammar: Grammar) -> Result<[u8; 27], ChallengeError> {
    let mut source_buffer = [0_u8; MAX_SOURCE_BYTES];
    let source = decode_source(encoded, &mut source_buffer)?;
    if grammar == Grammar::ExactTemplate {
        return exact_literals(source);
    }
    stock_literals(source)
}

fn decode_source<'a>(
    encoded: &[u8],
    source_buffer: &'a mut [u8; MAX_SOURCE_BYTES],
) -> Result<&'a [u8], ChallengeError> {
    if encoded.is_empty()
        || encoded.len() > MAX_SOURCE_BYTES * 2
        || !encoded.len().is_multiple_of(2)
    {
        return Err(DecodeError {
            kind: ErrorKind::InvalidLength,
            opcode: Some(b'6'),
            offset: 0,
        });
    }
    let mut key = 23_u8;
    let mut high = 0;
    for (index, &letter) in encoded.iter().enumerate() {
        if !letter.is_ascii_alphabetic() {
            return Err(error(index, ErrorKind::Alphabet));
        }
        let nibble = (letter.to_ascii_lowercase() - b'a' + 26 - key) % 26;
        if nibble > 15 {
            return Err(error(index, ErrorKind::Nibble));
        }
        if index % 2 == 0 {
            high = nibble << 4;
        } else {
            source_buffer[index / 2] = high | nibble;
        }
        key = (key + 17) % 26;
    }
    Ok(&source_buffer[..encoded.len() / 2])
}

fn stock_literals(source: &[u8]) -> Result<[u8; 27], ChallengeError> {
    let mut parser = Parser { source, offset: 0 };
    parser.tokens(&["var", "a", "="])?;
    let first = parser.literal(5)?;
    parser.tokens(&[";", "a", "+="])?;
    let second = parser.literal(22)?;
    parser.tokens(&[
        ";",
        "for",
        "(",
        "var",
        "i",
        "=",
        "0",
        ";",
        "i",
        "<",
        "27",
        ";",
        "i",
        "++",
        ")",
        "{",
        "idba",
        "[",
        "i",
        "]",
        "=",
        "a",
        ".",
        "charCodeAt",
        "(",
        "i",
        ")",
        ";",
        "}",
    ])?;
    parser.whitespace();
    if parser.offset != source.len() {
        return Err(error(parser.offset * 2, ErrorKind::Syntax));
    }

    let mut reply = [0_u8; 27];
    reply[..5].copy_from_slice(first);
    reply[5..].copy_from_slice(second);
    Ok(reply)
}

/// A reply to the general copy-loop grammar. Only `as_bytes()` is transmitted;
/// unused capacity is private. Its capacity shares the decoded-source bound.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CopyLoopReply {
    bytes: [u8; MAX_SOURCE_BYTES],
    len: usize,
}
impl CopyLoopReply {
    pub fn as_bytes(&self) -> &[u8] {
        &self.bytes[..self.len]
    }
    pub fn len(&self) -> usize {
        self.len
    }
    pub fn is_empty(&self) -> bool {
        self.len == 0
    }
}

/// Solve one or more nonempty printable ASCII literals followed by exactly one
/// `for(var i=0;i<N;i++)` copy into `idba[i]`, with an optional braced body.
/// Literals may use either quote, but cannot contain that delimiter or a
/// backslash. Token whitespace is allowed. N has 1..=3 decimal digits, no
/// leading zero and must equal the concatenated length. No code is evaluated.
///
/// Uses the stock start-3/step-4 rotation over N bytes, including JS signed
/// remainder. This is opt-in: the stock and simulator admission APIs retain
/// their existing grammars. Errors count encoded payload bytes, like `stock`.
pub fn copy_loop(encoded: &[u8]) -> Result<CopyLoopReply, ChallengeError> {
    let mut source_buffer = [0; MAX_SOURCE_BYTES];
    let source = decode_source(encoded, &mut source_buffer)?;
    let mut parser = Parser { source, offset: 0 };
    parser.tokens(&["var", "a", "="])?;
    let mut reply = CopyLoopReply {
        bytes: [0; MAX_SOURCE_BYTES],
        len: 0,
    };
    loop {
        let literal = parser.copy_literal()?;
        // Literals are disjoint slices of the bounded source, so their total
        // length cannot exceed capacity.
        reply.bytes[reply.len..reply.len + literal.len()].copy_from_slice(literal);
        reply.len += literal.len();
        parser.tokens(&[";"])?;
        parser.whitespace();
        if parser.source.get(parser.offset) != Some(&b'a') {
            break;
        }
        parser.tokens(&["a", "+="])?;
    }
    parser.tokens(&["for", "(", "var", "i", "=", "0", ";", "i", "<"])?;
    parser.whitespace();
    let count_offset = parser.offset;
    if parser.count()? != reply.len {
        return Err(error(count_offset * 2, ErrorKind::Literal));
    }
    parser.tokens(&[";", "i", "++", ")"])?;
    parser.whitespace();
    let braced = parser.source.get(parser.offset) == Some(&b'{');
    if braced {
        parser.tokens(&["{"])?;
    }
    parser.tokens(&[
        "idba",
        "[",
        "i",
        "]",
        "=",
        "a",
        ".",
        "charCodeAt",
        "(",
        "i",
        ")",
        ";",
    ])?;
    if braced {
        parser.tokens(&["}"])?;
    }
    parser.whitespace();
    if parser.offset != source.len() {
        return Err(error(parser.offset * 2, ErrorKind::Syntax));
    }
    rotate(&mut reply.bytes[..reply.len], 4);
    Ok(reply)
}

struct Parser<'a> {
    source: &'a [u8],
    offset: usize,
}

impl<'a> Parser<'a> {
    fn copy_literal(&mut self) -> Result<&'a [u8], ChallengeError> {
        self.whitespace();
        let quote = match self.source.get(self.offset) {
            Some(&quote @ (b'"' | b'\'')) => quote,
            _ => return Err(error(self.offset * 2, ErrorKind::Literal)),
        };
        let start = self.offset + 1;
        self.offset = start;
        while let Some(&c) = self.source.get(self.offset) {
            if c == quote {
                if self.offset == start {
                    return Err(error(self.offset * 2, ErrorKind::Literal));
                }
                let literal = &self.source[start..self.offset];
                self.offset += 1;
                return Ok(literal);
            }
            if !(b' '..=b'~').contains(&c) || c == b'\\' {
                return Err(error(self.offset * 2, ErrorKind::Literal));
            }
            self.offset += 1;
        }
        Err(error(self.offset * 2, ErrorKind::Literal))
    }

    fn count(&mut self) -> Result<usize, ChallengeError> {
        self.whitespace();
        let start = self.offset;
        while self.source.get(self.offset).is_some_and(u8::is_ascii_digit) {
            self.offset += 1;
        }
        let digits = &self.source[start..self.offset];
        if digits.is_empty() || digits[0] == b'0' || digits.len() > 3 {
            return Err(error(start * 2, ErrorKind::Syntax));
        }
        Ok(digits.iter().fold(0, |n, c| n * 10 + usize::from(c - b'0')))
    }

    fn whitespace(&mut self) {
        while self
            .source
            .get(self.offset)
            .is_some_and(|c| matches!(c, b' ' | b'\t' | b'\r' | b'\n'))
        {
            self.offset += 1;
        }
    }

    fn tokens(&mut self, expected: &[&str]) -> Result<(), ChallengeError> {
        for &token in expected {
            self.whitespace();
            let start = self.offset;
            let Some(&byte) = self.source.get(start) else {
                return Err(error(self.offset * 2, ErrorKind::Syntax));
            };
            if byte.is_ascii_alphabetic() || byte == b'_' {
                self.offset += 1;
                while self
                    .source
                    .get(self.offset)
                    .is_some_and(|c| c.is_ascii_alphanumeric() || *c == b'_')
                {
                    self.offset += 1;
                }
            } else if byte.is_ascii_digit() {
                self.offset += 1;
                while self.source.get(self.offset).is_some_and(u8::is_ascii_digit) {
                    self.offset += 1;
                }
            } else if self
                .source
                .get(start..start + 2)
                .is_some_and(|s| s == b"+=" || s == b"++")
            {
                self.offset += 2;
            } else {
                self.offset += 1;
            }
            if &self.source[start..self.offset] != token.as_bytes() {
                return Err(error(self.offset * 2, ErrorKind::Syntax));
            }
        }
        Ok(())
    }

    fn literal(&mut self, length: usize) -> Result<&'a [u8], ChallengeError> {
        self.whitespace();
        if self.source.get(self.offset) != Some(&b'"') {
            return Err(error(self.offset * 2, ErrorKind::Literal));
        }
        let start = self.offset + 1;
        let end = start + length;
        let literal = self
            .source
            .get(start..end)
            .ok_or(error(self.offset * 2, ErrorKind::Literal))?;
        if literal
            .iter()
            .any(|c| !(b' '..=b'~').contains(c) || matches!(c, b'"' | b'\\'))
            || self.source.get(end) != Some(&b'"')
        {
            return Err(error(self.offset * 2, ErrorKind::Literal));
        }
        self.offset = end + 1;
        Ok(literal)
    }
}
